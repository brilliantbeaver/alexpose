#!/usr/bin/env python3
"""Generate native agent profiles from .agents; Python 3.11+, standard library only.

Default mode checks without writing. --write regenerates owned outputs, refusing
unmanaged files or local edits. --prompt ID prints a complete portable role prompt.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys
import tomllib

ROOT = Path(__file__).resolve().parents[2]
STATE = '.agents/generated.json'


def destination(root: Path, relative: str) -> Path:
    root = root.resolve()
    fragment = Path(relative)
    if fragment.is_absolute() or '..' in fragment.parts:
        raise ValueError(f'Invalid output path: {relative}')
    target = root / fragment
    for part in (target, *target.parents):
        if part == root:
            break
        if part.is_symlink():
            raise ValueError(f'Refusing symlink output or ancestor: {relative}')
    if not target.resolve().is_relative_to(root):
        raise ValueError(f'Output escapes project: {relative}')
    return target


def digest(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def load_roles(root: Path) -> list[dict]:
    roles = []
    names = set()
    for source, family in [('.agents/general-roles.json', 'general'),
                           ('.agents/teams/sjepa/roles.json', 'sjepa')]:
        for item in json.loads((root / source).read_text()):
            role = dict(item, family=family)
            name = role['id']
            if not re.fullmatch(r'[a-z][a-z0-9]*(?:-[a-z0-9]+)*', name) or name in names:
                raise ValueError(f'Invalid or duplicate role ID: {name}')
            names.add(name)
            path = (root / role['source']).resolve()
            if not path.is_relative_to((root / '.agents').resolve()) or not path.is_file():
                raise ValueError(f'Invalid canonical source: {path}')
            if not role['description'].strip() or type(role['coordinator']) is not bool:
                raise ValueError(f'Invalid role contract: {name}')
            role['body'] = path.read_text()
            if not role['body'].strip():
                raise ValueError(f'Empty role: {name}')
            # Existing S-JEPA contracts remain byte-for-byte unchanged in Codex.
            role['prompt'] = ((root / '.agents/protocol.md').read_text() + '\n\n' + role['body']
                              if family == 'general' else role['body'])
            roles.append(role)
    return roles


def render(root: Path) -> tuple[dict[str, str], list[dict]]:
    outputs = {}
    roles = load_roles(root)
    for role in roles:
        name = role['id']
        codex_name = role.get('codex_name', name)
        if not re.fullmatch(r'[a-z][a-z0-9_-]*', codex_name):
            raise ValueError(f'Invalid Codex ID: {codex_name}')
        path = f'.codex/agents/{codex_name}.toml'
        if path in outputs:
            raise ValueError(f'Native identity collision: {path}')
        fields = {'name': codex_name, 'description': role['description'],
                  'developer_instructions': role['prompt']}
        # JSON basic strings are valid TOML basic strings for these Unicode texts.
        outputs[path] = '# Generated by .agents/scripts/sync_agents.py; edit canonical sources.\n' + ''.join(
            f'{key} = {json.dumps(value, ensure_ascii=False)}\n' for key, value in fields.items())
        tomllib.loads(outputs[path])
        header = ('---\n' + f'name: {json.dumps(name)}\n' +
                  f'description: {json.dumps(role["description"])}\n')
        if not role['coordinator']:
            header += 'disallowedTools: Agent\n'
        outputs[f'.claude/agents/{name}.md'] = (header + '---\n\n' +
            '<!-- Generated by .agents/scripts/sync_agents.py; edit canonical sources. -->\n\n' + role['prompt'])
        header = ('---\n' + f'description: {json.dumps(role["description"])}\n' +
                  f'mode: {"primary" if role["coordinator"] else "subagent"}\n')
        if not role['coordinator']:
            header += 'permissions:\n  - action: subagent\n    resource: "*"\n    effect: deny\n'
        outputs[f'.opencode/agents/{name}.md'] = (header + '---\n\n' +
            '<!-- Generated by .agents/scripts/sync_agents.py; edit canonical sources. -->\n\n' +
            'Host compatibility: OpenCode controls model, tools and permissions through its own '
            'configuration. Its actual controls and the metadata above are authoritative; '
            'references below to parent inheritance do not override OpenCode rules.\n\n' + role['prompt'])
    return outputs, roles


def synchronize(root: Path, write: bool = False) -> list[str]:
    outputs, roles = render(root)
    state_path = destination(root, STATE)
    old = json.loads(state_path.read_text())['files'] if state_path.exists() else {}
    stale = set(old) - set(outputs)
    if stale:
        raise ValueError('Retired outputs need explicit review/removal: ' + ', '.join(sorted(stale)))
    changed = []
    for path, expected in outputs.items():
        target = destination(root, path)
        if not target.exists():
            changed.append(path)
            continue
        current = target.read_text()
        if current == expected:
            continue
        # Import only semantically identical pre-existing S-JEPA Codex profiles.
        legacy = False
        if not old and path.startswith('.codex/agents/sjepa_'):
            try:
                legacy = tomllib.loads(current) == tomllib.loads(expected)
            except tomllib.TOMLDecodeError:
                pass
        if not legacy and (path not in old or digest(current) != old[path]):
            raise ValueError(f'Refusing unmanaged or locally edited output: {path}')
        changed.append(path)
    state = {'schema_version': 1, 'generator': '.agents/scripts/sync_agents.py',
             'role_count': len(roles), 'files': {p: digest(t) for p, t in sorted(outputs.items())}}
    state_text = json.dumps(state, indent=2) + '\n'
    if not state_path.exists() or state_path.read_text() != state_text:
        changed.append(STATE)
    # All collision checks precede any writes.
    if write:
        for path in changed:
            target = root / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(state_text if path == STATE else outputs[path])
    return changed


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--prompt', metavar='ROLE_ID')
    args = parser.parse_args()
    if args.write and args.prompt:
        parser.error('--prompt and --write cannot be combined')
    try:
        if args.prompt:
            role = next((r for r in load_roles(ROOT) if r['id'] == args.prompt), None)
            if role is None:
                raise ValueError(f'Unknown role: {args.prompt}')
            print(role['prompt'])
            return 0
        changed = synchronize(ROOT, args.write)
        if changed and not args.write:
            print('Generated profiles need synchronization:\n' + '\n'.join(changed), file=sys.stderr)
            return 1
        print(f'{"Updated" if args.write else "Verified"} {len(changed)} changed paths; '
              f'{len(load_roles(ROOT))} canonical roles across three native formats.')
        return 0
    except (ValueError, KeyError, OSError) as error:
        print(f'Agent synchronization failed: {error}', file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
