#!/usr/bin/env bash
# Prepare a CUDA 12.4 development toolkit without changing the system driver.
set -euo pipefail

usage() {
  cat <<'EOF'
Usage: bash slurm/synthetic-training/setup-cuda-toolkit.sh

Reuse a complete CUDA 12.4 toolkit at CUDA_HOME, or install NVIDIA's CUDA
12.4.1 toolkit in a dedicated directory. No Conda installation is required.

ST_TOOLCHAIN_ROOT defaults to /hai/scratch/$USER/toolchains/synthetic-training-cu124.
After this command succeeds, source "$ST_TOOLCHAIN_ROOT/cuda.env" in Bash.
The generated file sets CUDA_HOME and adds its compiler to PATH.
EOF
}
fail() { echo "CUDA toolkit setup: $*" >&2; exit 1; }
case "${1:-}" in
  -h|--help) usage; exit 0 ;;
  "") [[ "$#" == 0 ]] || fail "This command takes no arguments." ;;
  *) usage >&2; fail "Unknown option: $1" ;;
esac

[[ "$(uname -s)" == Linux && "$(uname -m)" == x86_64 ]] ||
  fail "Run this command on HAIC (Linux x86_64)."
export ST_TOOLCHAIN_ROOT="${ST_TOOLCHAIN_ROOT:-/hai/scratch/${USER:?}/toolchains/synthetic-training-cu124}"
[[ "$ST_TOOLCHAIN_ROOT" == /* ]] || fail "ST_TOOLCHAIN_ROOT must be an absolute path."
case "$ST_TOOLCHAIN_ROOT" in
  /|/usr|/usr/local|/opt|"$HOME") fail "Choose a dedicated ST_TOOLCHAIN_ROOT directory." ;;
esac
command -v flock >/dev/null || fail "The flock command is required."
mkdir -p "$ST_TOOLCHAIN_ROOT"
exec 9> "$ST_TOOLCHAIN_ROOT/setup.lock"
flock --nonblock 9 || fail "Another toolkit setup is running. Retry after it finishes."

# A runtime supplied by Torch is not a compiler installation. Check both.
valid_toolkit() {
  local candidate="$1" header library_dir
  [[ "$candidate" == /* && -x "$candidate/bin/nvcc" ]] || return 1
  "$candidate/bin/nvcc" --version 2>/dev/null |
    grep -Eq 'release 12\.4([,[:space:]]|$)' || return 1
  for header in cuda.h cuda_runtime.h cuda_fp16.h cublas_v2.h cusparse.h; do
    [[ -f "$candidate/include/$header" ]] || return 1
  done
  for library_dir in "$candidate/lib64" "$candidate/lib"; do
    [[ -f "$library_dir/libcudart.so" ]] && return 0
  done
  return 1
}

managed_toolkit="$ST_TOOLCHAIN_ROOT/cuda-12.4.1"
if [[ -n "${CUDA_HOME:-}" ]] && valid_toolkit "$CUDA_HOME"; then
  toolkit="$CUDA_HOME"
  echo "Using the verified CUDA 12.4 toolkit: $toolkit"
else
  if [[ -n "${CUDA_HOME:-}" ]]; then
    echo "CUDA_HOME=$CUDA_HOME is not a complete CUDA 12.4 toolkit; using the managed installation."
  fi
  toolkit="$managed_toolkit"
  if ! valid_toolkit "$toolkit"; then
    for program in curl sha256sum; do
      command -v "$program" >/dev/null || fail "Required command '$program' is missing."
    done

    # A failed package transaction can be reconciled using its Conda metadata.
    # An unrelated or unrecognizable directory is preserved for inspection.
    operation=create
    if [[ -e "$toolkit" ]]; then
      [[ -f "$toolkit/conda-meta/history" ]] ||
        fail "$toolkit exists but is incomplete or unrecognized. Set ST_TOOLCHAIN_ROOT to a fresh directory and rerun; the existing files were preserved."
      operation=install
      echo "Resuming the toolkit installation in $toolkit"
    fi

    micromamba="$ST_TOOLCHAIN_ROOT/bin/micromamba-2.8.1"
    micromamba_sha256=9689782d863c05a1bf5d2d371ba527104e7a4eb4310c1637d8653b751aed9c82
    mkdir -p "$ST_TOOLCHAIN_ROOT/bin"
    if [[ ! -f "$micromamba" ]] ||
      ! printf '%s  %s\n' "$micromamba_sha256" "$micromamba" | sha256sum --check --status; then
      echo "Downloading the pinned micromamba 2.8.1 installer."
      curl --fail --location --retry 3 \
        https://github.com/mamba-org/micromamba-releases/releases/download/2.8.1-0/micromamba-linux-64 \
        --output "$micromamba.download"
      printf '%s  %s\n' "$micromamba_sha256" "$micromamba.download" | sha256sum --check ||
        fail "The micromamba checksum did not match. Rerun to download it again."
      chmod +x "$micromamba.download"
      mv "$micromamba.download" "$micromamba"
    fi
    chmod +x "$micromamba"

    echo "Installing CUDA 12.4.1 in $toolkit (about 3.5 GiB to download)."
    "$micromamba" --no-rc --no-env "$operation" --yes \
      --root-prefix "$ST_TOOLCHAIN_ROOT/micromamba" \
      --prefix "$toolkit" --override-channels \
      --channel https://conda.anaconda.org/nvidia/label/cuda-12.4.1 \
      'cuda-toolkit=12.4.1'
    valid_toolkit "$toolkit" ||
      fail "The package command finished, but CUDA compiler/header/library checks failed in $toolkit. Preserve its output and retry this command."
  fi
fi

# Publish shell configuration only after all checks pass. printf %q quotes paths
# safely for Bash; no package output is evaluated as shell code.
env_file="$(mktemp "$ST_TOOLCHAIN_ROOT/cuda.env.XXXXXX")"
{
  printf '# Generated by setup-cuda-toolkit.sh; source this file in Bash.\n'
  printf 'export ST_TOOLCHAIN_ROOT=%q\n' "$ST_TOOLCHAIN_ROOT"
  printf 'export CUDA_HOME=%q\n' "$toolkit"
  printf 'export PATH="$CUDA_HOME/bin:$PATH"\n'
} > "$env_file"
mv "$env_file" "$ST_TOOLCHAIN_ROOT/cuda.env"
"$toolkit/bin/nvcc" --version
printf 'CUDA_TOOLKIT_PASSED\nSource in Bash: %s/cuda.env\n' "$ST_TOOLCHAIN_ROOT"
